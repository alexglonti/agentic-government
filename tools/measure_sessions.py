#!/usr/bin/env python3
"""Read-only metrics extractor for Claude Code session transcripts.

Walks <projects-dir>/<project>/<session>.jsonl (the main transcript of each
session) plus <projects-dir>/<project>/<session>/subagents/*.jsonl (delegated
agent transcripts, attributed to the parent session), streams every file line
by line, and writes one CSV row per session with numbers only - no message
text is copied.

Each session gets an era label: "baseline" if it started before the cutoff,
"government" otherwise. The default cutoff is the creation time of the
agentic-government SKILL.md under the user's Claude config, if it exists.

Usage:
  python -I measure_sessions.py [--projects-dir DIR] [--cutoff ISO|--cutoff-file PATH]
                                [--csv OUT.csv] [--report OUT.md] [--idle-gap-min 30]

The REWORK column is a HEURISTIC: a real user turn counts as a "correction"
if it contains one of a fixed list of words (see REWORK_WORDS). It cannot
tell a real correction from an ordinary sentence that happens to use them.
"""
import argparse
import csv
import datetime as dt
import glob
import json
import os
import re
import sys
from collections import Counter, defaultdict

REWORK_WORDS = [
    "no", "not", "wrong", "fix", "again", "doesn't", "didn't", "forgot",
    "sucks", "fucked", "bad", "still", "isn't", "redo", "remove",
]
# word-boundary match; accept straight or curly apostrophes
_rw = [re.escape(w).replace("'", "['’]") for w in REWORK_WORDS]
REWORK_RE = re.compile(r"(?<![\w'’])(?:" + "|".join(_rw) + r")(?![\w'’])", re.I)

# user text that is generated by the harness, not typed by a person
SYNTHETIC_PREFIXES = (
    "<command-name>", "<command-message>", "<command-args>", "<local-command-",
    "<task-notification>", "<system-reminder>", "[Request interrupted",
    "Caveat:", "This session is being continued", "<bash-input>", "<bash-stdout>",
    "<bash-stderr>", "<user-prompt-submit-hook>", "[Image:",
)

TASK_NOTE_RE = re.compile(
    r"<task-id>([^<]+)</task-id>.*?<subagent_tokens>(\d+)</subagent_tokens>"
    r"(?:.*?<tool_uses>(\d+)</tool_uses>)?.*?<duration_ms>(\d+)</duration_ms>",
    re.S,
)

FIELDS = [
    "session_id", "session_short", "project", "era", "start_utc", "end_utc",
    "wall_minutes", "active_minutes", "user_turns", "rework_turns", "rework_pct",
    "peer_turns", "assistant_turns", "input_tokens", "output_tokens", "cache_creation_tokens",
    "cache_read_tokens", "total_tokens", "tool_calls", "tool_errors",
    "tool_error_pct", "subagent_runs", "subagent_tokens", "subagent_minutes",
    "subagent_files", "subagent_file_tokens", "main_model", "split", "bytes", "bad_lines",
]


def parse_ts(s):
    if not s or not isinstance(s, str):
        return None
    try:
        return dt.datetime.fromisoformat(s.replace("Z", "+00:00")).astimezone(dt.timezone.utc)
    except ValueError:
        return None


def default_cutoff_file():
    return os.path.join(os.path.expanduser("~"), ".claude", "skills", "agentic-government", "SKILL.md")


def file_creation_utc(path):
    st = os.stat(path)
    # st_birthtime on Windows (py3.12+) / macOS; fall back to ctime (creation on Windows)
    t = getattr(st, "st_birthtime", None) or st.st_ctime
    return dt.datetime.fromtimestamp(t, dt.timezone.utc)


def user_text(rec):
    """Return the typed text of a real user turn, or None."""
    if rec.get("type") != "user" or rec.get("isMeta") or rec.get("isSidechain"):
        return None
    if rec.get("isCompactSummary") or rec.get("isVisibleInTranscriptOnly"):
        return None
    origin = rec.get("origin")
    if isinstance(origin, dict) and origin.get("kind") not in (None, "human"):
        return None
    msg = rec.get("message")
    if not isinstance(msg, dict):
        return None
    cont = msg.get("content")
    if isinstance(cont, str):
        text = cont
    elif isinstance(cont, list):
        if any(isinstance(b, dict) and b.get("type") == "tool_result" for b in cont):
            return None
        text = " ".join(b.get("text", "") for b in cont if isinstance(b, dict) and b.get("type") == "text")
        if not text.strip() and any(isinstance(b, dict) and b.get("type") == "image" for b in cont):
            return "[image]"  # a pasted screenshot with no text is still a real user turn
    else:
        return None
    t = text.strip()
    if not t or t.startswith(SYNTHETIC_PREFIXES):
        return None
    return t


def usage_tokens(path):
    """Sum de-duplicated usage of one transcript.

    Returns ([in, out, cache_write, cache_read], messages, bad lines, first timestamp).
    """
    per_msg = {}
    bad = 0
    first = None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            try:
                rec = json.loads(line)
            except ValueError:
                bad += 1
                continue
            if not isinstance(rec, dict):
                continue
            ts = parse_ts(rec.get("timestamp"))
            if ts and (first is None or ts < first):
                first = ts
            if rec.get("type") != "assistant":
                continue
            msg = rec.get("message") or {}
            u = msg.get("usage")
            if not isinstance(u, dict):
                continue
            key = msg.get("id") or rec.get("requestId") or rec.get("uuid")
            cur = per_msg.setdefault(key, [0, 0, 0, 0])
            vals = [u.get("input_tokens") or 0, u.get("output_tokens") or 0,
                    u.get("cache_creation_input_tokens") or 0, u.get("cache_read_input_tokens") or 0]
            per_msg[key] = [max(a, b) for a, b in zip(cur, vals)]
    tot = [sum(v[i] for v in per_msg.values()) for i in range(4)]
    return tot, len(per_msg), bad, first


class _Bucket:
    """Counters for one (session, era) segment."""

    def __init__(self):
        self.times = []
        self.user_turns = 0
        self.rework = 0
        self.peer_turns = 0
        self.per_msg = {}
        self.model_by_msg = {}
        self.tool_calls = 0
        self.tool_errors = 0
        self.tasks = set()
        self.sub_files = 0
        self.sub_file_tokens = 0


def _era(ts, cutoff):
    return "government" if ts >= cutoff else "baseline"


def scan_session(path, idle_gap_min, cutoff, split):
    """Scan one main transcript. Returns (rows, bad_lines).

    With split=True each event goes to the era of its own timestamp, so a
    session that spans the cutoff yields two rows. With split=False the whole
    session goes to the era of its first event.
    """
    sid = os.path.splitext(os.path.basename(path))[0]
    project = os.path.basename(os.path.dirname(path))
    buckets = defaultdict(_Bucket)
    tool_ids = set()
    msg_era = {}
    bad = 0
    cur_ts = None
    session_start = None

    def era_of(ts):
        if not split:
            return _era(session_start, cutoff) if session_start else "baseline"
        return _era(ts, cutoff) if ts else "baseline"

    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            try:
                rec = json.loads(line)
            except ValueError:
                bad += 1
                continue
            if not isinstance(rec, dict):
                continue
            ts = parse_ts(rec.get("timestamp"))
            if ts:
                cur_ts = ts if cur_ts is None or ts > cur_ts else cur_ts
            if ts and rec.get("type") in ("user", "assistant", "system", "attachment"):
                if session_start is None or ts < session_start:
                    session_start = ts
                buckets[era_of(ts)].times.append(ts)
            bk = buckets[era_of(ts or cur_ts)] if (ts or cur_ts) else None
            if "<subagent_tokens>" in line and bk is not None:
                for m in TASK_NOTE_RE.finditer(line):
                    bk.tasks.add((m.group(1).strip(), int(m.group(2)), int(m.group(4))))
            if bk is None or rec.get("isSidechain"):
                continue
            typ = rec.get("type")
            msg = rec.get("message") if isinstance(rec.get("message"), dict) else {}
            if typ == "assistant":
                key = msg.get("id") or rec.get("requestId") or rec.get("uuid")
                u = msg.get("usage")
                if isinstance(u, dict):
                    # one API message is written as several records; keep it in the era it first appeared
                    e = msg_era.setdefault(key, era_of(ts or cur_ts))
                    b2 = buckets[e]
                    vals = [u.get("input_tokens") or 0, u.get("output_tokens") or 0,
                            u.get("cache_creation_input_tokens") or 0, u.get("cache_read_input_tokens") or 0]
                    cur = b2.per_msg.get(key, [0, 0, 0, 0])
                    b2.per_msg[key] = [max(x, y) for x, y in zip(cur, vals)]
                    if msg.get("model") and msg["model"] != "<synthetic>":
                        b2.model_by_msg[key] = msg["model"]
                for b in msg.get("content") or []:
                    if isinstance(b, dict) and b.get("type") == "tool_use":
                        bid = b.get("id")
                        if bid not in tool_ids:
                            tool_ids.add(bid)
                            bk.tool_calls += 1
            elif typ == "user":
                cont = msg.get("content")
                if isinstance(cont, list):
                    for b in cont:
                        if isinstance(b, dict) and b.get("type") == "tool_result" and b.get("is_error"):
                            bk.tool_errors += 1
                origin = rec.get("origin")
                if isinstance(origin, dict) and origin.get("kind") == "peer":
                    bk.peer_turns += 1
                t = user_text(rec)
                if t is not None:
                    bk.user_turns += 1
                    if REWORK_RE.search(t):
                        bk.rework += 1

    # subagent transcript files next to the session, each assigned by its first timestamp
    sub_dir = os.path.join(os.path.dirname(path), sid, "subagents")
    for sf in sorted(glob.glob(os.path.join(sub_dir, "*.jsonl"))):
        st, _, b2, first = usage_tokens(sf)
        bad += b2
        e = era_of(first) if first else era_of(session_start)
        buckets[e].sub_files += 1
        buckets[e].sub_file_tokens += sum(st)

    rows = []
    for era, bk in buckets.items():
        times = sorted(bk.times)
        if not times:
            continue
        first, last = times[0], times[-1]
        active = 0.0
        for a, b in zip(times, times[1:]):
            g = (b - a).total_seconds() / 60.0
            if g <= idle_gap_min:
                active += g
        tot = [sum(v[i] for v in bk.per_msg.values()) for i in range(4)]
        model = Counter(bk.model_by_msg.values()).most_common(1)
        rows.append({
            "session_id": sid,
            "session_short": sid[:8],
            "project": project,
            "era": era,
            "start_utc": first.isoformat().replace("+00:00", "Z"),
            "end_utc": last.isoformat().replace("+00:00", "Z"),
            "_start": first,
            "wall_minutes": round((last - first).total_seconds() / 60.0, 1),
            "active_minutes": round(active, 1),
            "user_turns": bk.user_turns,
            "rework_turns": bk.rework,
            "rework_pct": round(100.0 * bk.rework / bk.user_turns, 1) if bk.user_turns else 0.0,
            "peer_turns": bk.peer_turns,
            "assistant_turns": len(bk.per_msg),
            "input_tokens": tot[0],
            "output_tokens": tot[1],
            "cache_creation_tokens": tot[2],
            "cache_read_tokens": tot[3],
            "total_tokens": sum(tot),
            "tool_calls": bk.tool_calls,
            "tool_errors": bk.tool_errors,
            "tool_error_pct": round(100.0 * bk.tool_errors / bk.tool_calls, 1) if bk.tool_calls else 0.0,
            # delegated agents: one per (task, tokens, duration) - repeated deliveries are dropped
            "subagent_runs": len(bk.tasks),
            "subagent_tokens": sum(t[1] for t in bk.tasks),
            "subagent_minutes": round(sum(t[2] for t in bk.tasks) / 60000.0, 1),
            "subagent_files": bk.sub_files,
            "subagent_file_tokens": bk.sub_file_tokens,
            "main_model": model[0][0] if model else "",
            "split": "yes" if split and len(buckets) > 1 else "",
            "bytes": os.path.getsize(path),
            "bad_lines": bad,
        })
    return rows, bad


def fmt_int(n):
    return f"{n:,}"


def era_totals(rows):
    t = Counter()
    for r in rows:
        for k in ("wall_minutes", "active_minutes", "user_turns", "rework_turns", "peer_turns", "assistant_turns",
                  "input_tokens", "output_tokens", "cache_creation_tokens", "cache_read_tokens",
                  "total_tokens", "tool_calls", "tool_errors", "subagent_runs", "subagent_tokens",
                  "subagent_minutes", "subagent_files", "subagent_file_tokens"):
            t[k] += r[k]
    t["sessions"] = len({r["session_id"] for r in rows})
    return t


def write_report(path, rows, skipped, cutoff, cutoff_src, idle_gap, split):
    eras = defaultdict(list)
    for r in rows:
        eras[r["era"]].append(r)
    L = []
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    L.append("# Baseline: pre-government vs Agentic Government\n")
    L.append(f"Generated {now} by `tools/measure_sessions.py` (read-only). Numbers only, no message text.\n")
    L.append(f"Cutoff: **{cutoff.strftime('%Y-%m-%d %H:%M:%S UTC')}** ({cutoff_src}). " +
             ("Each event is counted in the era of its own timestamp, so a session that spans the cutoff "
              "appears once per era (marked split).\n" if split else "A session's era is set by its start time.\n"))
    L.append("## Totals per era\n")
    L.append("| Metric | " + " | ".join(sorted(eras)) + " |")
    L.append("|---|" + "---|" * len(eras))
    tots = {e: era_totals(v) for e, v in eras.items()}
    def row(label, fn):
        L.append(f"| {label} | " + " | ".join(fn(tots[e]) for e in sorted(eras)) + " |")
    row("Sessions (with activity in this era)", lambda t: str(t["sessions"]))
    row("Wall minutes (first to last event)", lambda t: fmt_int(round(t["wall_minutes"])))
    row(f"Active minutes (gaps > {idle_gap} min dropped)", lambda t: fmt_int(round(t["active_minutes"])))
    row("Real user turns", lambda t: fmt_int(t["user_turns"]))
    row("Rework turns (heuristic)", lambda t: fmt_int(t["rework_turns"]))
    row("Rework rate (heuristic)", lambda t: f"{100*t['rework_turns']/t['user_turns']:.1f}%" if t["user_turns"] else "-")
    row("Messages relayed from other sessions", lambda t: fmt_int(t["peer_turns"]))
    row("Assistant API turns", lambda t: fmt_int(t["assistant_turns"]))
    row("Input tokens (uncached)", lambda t: fmt_int(t["input_tokens"]))
    row("Output tokens", lambda t: fmt_int(t["output_tokens"]))
    row("Cache-write tokens", lambda t: fmt_int(t["cache_creation_tokens"]))
    row("Cache-read tokens", lambda t: fmt_int(t["cache_read_tokens"]))
    row("Total tokens (main sessions)", lambda t: fmt_int(t["total_tokens"]))
    row("Tool calls", lambda t: fmt_int(t["tool_calls"]))
    row("Tool errors", lambda t: fmt_int(t["tool_errors"]))
    row("Tool error rate", lambda t: f"{100*t['tool_errors']/t['tool_calls']:.1f}%" if t["tool_calls"] else "-")
    row("Delegated agent runs (notifications)", lambda t: fmt_int(t["subagent_runs"]))
    row("Delegated agent tokens (notifications)", lambda t: fmt_int(t["subagent_tokens"]))
    row("Delegated agent minutes (notifications)", lambda t: fmt_int(round(t["subagent_minutes"])))
    row("Subagent transcript files", lambda t: fmt_int(t["subagent_files"]))
    row("Subagent transcript tokens (all usage fields)", lambda t: fmt_int(t["subagent_file_tokens"]))
    row("Tokens per user turn (main)", lambda t: fmt_int(round(t["total_tokens"] / t["user_turns"])) if t["user_turns"] else "-")
    row("Output tokens per user turn", lambda t: fmt_int(round(t["output_tokens"] / t["user_turns"])) if t["user_turns"] else "-")
    L.append("")
    L.append("## Sessions\n")
    L.append("| Session | Project | Era | Start (UTC) | Wall min | Active min | Tokens | Output tok | User turns | Rework % | Tool calls | Tool errors | Agent runs | Agent tokens |")
    L.append("|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for r in sorted(rows, key=lambda r: r["start_utc"]):
        L.append("| {session_short} | {project} | {era}{sp} | {s} | {wall_minutes} | {active_minutes} | {tt} | {ot} | {user_turns} | {rework_pct} | {tool_calls} | {tool_errors} | {subagent_runs} | {st} |".format(
            sp=" (split)" if r["split"] else "", s=r["start_utc"][:16].replace("T", " "), tt=fmt_int(r["total_tokens"]),
            ot=fmt_int(r["output_tokens"]), st=fmt_int(r["subagent_tokens"]), **r))
    L.append("")
    L.append("## Skipped files\n")
    if skipped:
        for p, why in skipped:
            L.append(f"- `{p}`: {why}")
    else:
        L.append("- none")
    L.append("")
    L.append("## Caveats\n")
    for c in CAVEATS:
        L.append(f"- {c}")
    L.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))


CAVEATS = [
    "Rework is a keyword heuristic. It counts a user turn as a correction if it contains any of: "
    + ", ".join(REWORK_WORDS) + ". \"no\" and \"not\" appear in normal instructions (\"do not push\"), "
    "so it over-counts; a correction phrased without those words (\"use the blue one instead\") is missed. "
    "Use it to compare eras, not as an absolute rate.",
    "The heuristic cannot tell who caused the rework (the agent, the developer changing his mind, or a tool), "
    "nor how big the redo was.",
    "Real user turns are user records with typed text; tool results, slash-command output, task notifications, "
    "messages relayed from other sessions, image placeholders and compaction summaries are excluded. "
    "A relayed message from the secretary is therefore not a user turn even if it carries the developer's words.",
    "Tokens are summed per API message (de-duplicated by message id). Cache-read tokens dominate the total and "
    "cost far less per token than output; compare output and uncached input separately.",
    "Wall minutes run from the first to the last event, so a session left open overnight looks long; "
    "active minutes drop idle gaps above the cap but still include time the developer spent reading.",
    "Delegated agent numbers come from task notifications (tokens and duration as reported by the harness, "
    "repeated deliveries removed). Foreground agents that never send a notification only show up in the "
    "subagent transcript file count/tokens. The two token columns use different definitions and do not add up.",
    "By default every event is assigned to the era of its own timestamp, so the part of a long-running session "
    "after the cutoff counts as government work (rows marked split). With --no-split the whole session goes to "
    "the era of its start. Work in a split session after the cutoff may still be done the old way.",
    "Messages relayed from other Claude sessions (e.g. the secretary) are counted separately as relayed messages; "
    "a session driven only by relays shows 0 user turns.",
    "Tool errors are tool_result blocks flagged is_error. A denied permission prompt or a user interrupt also "
    "counts as an error; a tool that ran but did the wrong thing does not.",
    "Only transcripts still on disk are counted; deleted or cleaned-up sessions are invisible.",
    "Transcripts do not record the harness's side calls (session titles, compaction summaries, small Haiku "
    "helpers), so uncached input tokens are under-counted compared with the harness's own cost record. "
    "Cache and output tokens usually agree with that record within a few percent, but some sessions differ "
    "by about 10% on cache reads, because the cost record can cover a longer process lifetime than the transcript.",
    "A live session is measured up to the moment the script runs; re-run for final numbers.",
]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--projects-dir", default=os.path.join(os.path.expanduser("~"), ".claude", "projects"))
    ap.add_argument("--cutoff", help="ISO timestamp; sessions starting at/after it are 'government'")
    ap.add_argument("--cutoff-file", default=default_cutoff_file(),
                    help="use this file's creation time as the cutoff (default: agentic-government SKILL.md)")
    ap.add_argument("--csv", default="sessions.csv")
    ap.add_argument("--report", default=None, help="optional Markdown report path")
    ap.add_argument("--idle-gap-min", type=float, default=30.0)
    ap.add_argument("--no-split", action="store_true",
                    help="assign whole sessions to the era of their start instead of splitting at the cutoff")
    a = ap.parse_args()

    if a.cutoff:
        cutoff = parse_ts(a.cutoff)
        if cutoff is None:
            sys.exit("bad --cutoff")
        src = "--cutoff argument"
    elif a.cutoff_file and os.path.exists(a.cutoff_file):
        cutoff = file_creation_utc(a.cutoff_file)
        src = "creation time of " + os.path.basename(os.path.dirname(a.cutoff_file)) + "/" + os.path.basename(a.cutoff_file)
    else:
        sys.exit("no cutoff: pass --cutoff or an existing --cutoff-file")

    rows, skipped = [], []
    for path in sorted(glob.glob(os.path.join(a.projects_dir, "*", "*.jsonl"))):
        rel = os.path.relpath(path, a.projects_dir)
        try:
            srows, _ = scan_session(path, a.idle_gap_min, cutoff, not a.no_split)
        except OSError as e:
            skipped.append((rel, f"unreadable ({e.__class__.__name__})"))
            continue
        if not srows:
            skipped.append((rel, "no timestamped records (metadata-only or empty)"))
            continue
        if all(r["assistant_turns"] == 0 and r["user_turns"] == 0 for r in srows):
            skipped.append((rel, "no user or assistant turns"))
            continue
        for r in srows:
            rows.append(r)
            print(f"{r['session_short']} {r['era']:<10} {r['bytes']/1e6:8.1f} MB  tokens={r['total_tokens']:,}",
                  file=sys.stderr)

    os.makedirs(os.path.dirname(os.path.abspath(a.csv)), exist_ok=True)
    with open(a.csv, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, extrasaction="ignore")
        w.writeheader()
        for r in sorted(rows, key=lambda r: r["start_utc"]):
            w.writerow(r)
    if a.report:
        write_report(a.report, rows, skipped, cutoff, src, a.idle_gap_min, not a.no_split)
    print(f"{len({r['session_id'] for r in rows})} sessions in {len(rows)} rows, {len(skipped)} skipped, cutoff {cutoff.isoformat()}", file=sys.stderr)
    for p, why in skipped:
        print(f"skipped {p}: {why}", file=sys.stderr)


if __name__ == "__main__":
    main()
